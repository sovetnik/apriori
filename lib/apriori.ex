defmodule Apriori do
  @moduledoc """
  **Apriori** — transcendental optics of cognition.

  ## De Aprioritate

  Nomen **a priori** venit ex philosophia transcendentali Kantiana
  (*Kritik der reinen Vernunft*): illae formae cognitionis quae *ante omnem
  experientiam* in intellectu nostro iam insunt — non ex mundo acceptae,
  sed conditiones ipsae per quas mundum intelligere possumus.

  Kant demonstravit quod nos res non cognoscimus "ut sunt in se" (*Ding an sich*),
  sed tantum ut *nobis apparent* — per formas a priori intuitionis et intellectus.
  Spatium et tempus sunt formae sensibilitatis; categoriae (unitas, pluralitas,
  causalitas, etc.) sunt formae intellectus. Sine his formis, cognitio impossibilis est.

  **Apriori** est applicatio huius philosophiae ad cognitionem systematicam:
  definitio formarum et modorum per quos systema phaenomena ordinare et
  intelligere potest. Non est "data format" (res empirica), sed **conditio
  possibilitatis** cognitionis ipsius.

  ## Tres Elementa Transcendentalia

  - **Phaenomenon** — *quod apparet* (eventus ante interpretationem)
    Analogon sensationis: datum purum, nondum formatum.

  - **Forma** — *in qua forma significatio tenetur*
    Analogon formarum intuitionis: Essentia (unitas), Collectio (pluralitas),
    Absentia (negatio), Sententia (iudicium). Categoriae per quas contentus
    in intellectu ordinatur.

  - **Modus** — *genus actus cognitionis*
    Analogon functionum iudicii: Quaestio (theoria), Intentio (praxis),
    Notificatio (receptio). Determinat quomodo intellectus se ad phaenomenon refert.

  Haec tria non sunt "implementationes" (res technicae), sed **categoriae
  transcendentales** — conditiones sine quibus systema phaenomena cognoscere
  non potest.

  ## Fundamentum Ecosystematis

  **Apriori** non habet codicem executabilem. Est ontologia pura, typus-systemata.

  Sed est fundamentum totius ecosystematis Umwelt: omne systema quod cum
  phaenomenis operatur debet illa per formas Apriori interpretare.
  Alioquin, chaos: nullum *Ding* sine *Form*, nullum *Actus* sine *Modus*.

  Aussenwelt (protocolum externum) variare potest — sed semper per Apriori
  formas traducitur. Sicut Kant: licet sensationes varient, formae a priori
  manent eaedem.

  ## Dependentia Transcendentalis

  Cur Apriori centrum est?

  Non quia "omnia ab eo dependent" (dependentia technica causalis), sed quia
  **omnia per ipsum intelliguntur** (dependentia transcendentalis logica).

  Sicut spatium est conditio possibilitatis visionis externae, et tempus
  conditio possibilitatis experientiae internae — ita Forma et Modus sunt
  conditiones possibilitatis cognitionis systematicae.

  Systema sine Apriori non est systema imperfectum, sed *impossibile*:
  nullum "cogitare" sine categoriis per quas cogitatio ordinatur.

  ## Vide Etiam

  - `Apriori.Phaenomenon` — quod apparet (datum ante formam)
  - `Apriori.Forma` — categoriae contentus (Essentia, Collectio, Absentia...)
  - `Apriori.Modus` — categoriae actus (Quaestio, Intentio, Operatio...)
  - `Umwelt` — architectura per quam formae applicantur (Merkwelt, Verstand, Wirkwelt)
  """
end
